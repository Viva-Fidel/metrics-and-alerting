// Package main реализует multichecker — единую точку запуска статического анализа проекта.
//
// # Запуск
//
// Из корня репозитория:
//
//	go run ./cmd/staticlint ./...
//
// Для проверки конкретного пакета:
//
//	go run ./cmd/staticlint ./internal/...
//
// Multichecker принимает стандартные флаги go/analysis, в том числе:
//
//   - -test: анализировать тестовые файлы;
//   - -fix: применить автоматические исправления (если анализатор их поддерживает).
//
// При обнаружении проблем инструмент завершается с ненулевым кодом.
//
// # Состав анализаторов
//
// ## Стандартные анализаторы golang.org/x/tools/go/analysis/passes
//
// Включены все публичные анализаторы пакета passes, в том числе:
//
//   - appends — некорректное использование append;
//   - asmdecl — ошибки в объявлениях ассемблерных функций;
//   - assign — бесполезные присваивания;
//   - atomic — некорректное использование sync/atomic;
//   - atomicalign — невыровненные 64-битные atomic-поля;
//   - bools — подозрительные булевы выражения;
//   - buildtag — некорректные build-теги;
//   - cgocall — нарушения правил вызова C из Go;
//   - composite — некорректные composite literals;
//   - copylock — копирование значений, содержащих sync.Locker;
//   - deepequalerrors — сравнение ошибок через reflect.DeepEqual;
//   - defers — проблемы с defer;
//   - directive — некорректные директивы go:...;
//   - errorsas — некорректное использование errors.As;
//   - fieldalignment — неоптимальный порядок полей структур;
//   - hostport — некорректные литералы host:port;
//   - httpresponse — утечка тел HTTP-ответов;
//   - ifaceassert — небезопасные type assertion к интерфейсам;
//   - loopclosure — захват переменных цикла в замыканиях;
//   - lostcancel — утечка context.CancelFunc;
//   - nilfunc — сравнение функций с nil;
//   - printf — ошибки форматирования в printf-подобных вызовах;
//   - shadow — затенение переменных;
//   - shift — подозрительные побитовые сдвиги;
//   - sigchanyzer — некорректное использование каналов сигналов;
//   - slog — ошибки в вызовах log/slog;
//   - sortslice — некорректная сортировка срезов;
//   - sqlrowserr — необработанная ошибка rows.Err;
//   - structtag — некорректные struct tags;
//   - testinggoroutine — вызовы t.Fatal из не-тестовой горутины;
//   - tests — ошибки в тестах;
//   - timeformat — некорректный формат времени;
//   - unmarshal — ошибки json/xml unmarshal;
//   - unreachable — недостижимый код;
//   - unsafeptr — небезопасные преобразования unsafe.Pointer;
//   - unusedresult — игнорирование результатов важных вызовов;
//   - unusedwrite — бесполезные записи в поля/переменные;
//   - waitgroup — некорректное использование sync.WaitGroup;
//   - modernize — рекомендации по модернизации кода (набор анализаторов Suite).
//
// ## Анализаторы staticcheck класса SA
//
// Подключены все анализаторы пакета honnef.co/go/tools/staticcheck (префикс SA).
// Они выявляют ошибки, проблемы производительности и потенциальные баги:
// некорректные регулярные выражения, устаревшие API, подозрительные сравнения,
// ошибки работы с горутинами, defer, HTTP, JSON и другими подсистемами.
//
// ## Анализаторы других классов staticcheck
//
//   - simple (S1xxx) — упрощения и идиоматичный Go-код;
//   - stylecheck (ST1xxx) — стилистические рекомендации и соглашения.
//
// ## Сторонние публичные анализаторы
//
//   - errcheck — необработанные ошибки возвращаемых значений;
//   - bodyclose — незакрытые HTTP response body.
//
// ## Собственный анализатор noosexit
//
// Пакет cmd/staticlint/noosexit запрещает прямой вызов os.Exit в функции main
// пакета main. Это упрощает тестирование точки входа и позволяет корректно
// выполнять отложенные вызовы (defer) перед завершением программы.
